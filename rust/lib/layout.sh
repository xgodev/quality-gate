#!/usr/bin/env bash
# Crate-layout metrics for the Rust gate (issue #26).
#
# A crate is Rust's unit of incremental compilation: editing one `.rs` file
# recompiles the whole crate and relinks everything above it. Two layouts make
# every edit slow, and no cargo tool reports either:
#
#   1. codegen mixed with hand-written code -- a crate whose `build.rs`
#      generates Rust (slint_build, tonic/prost-build, bindgen, ...) and that
#      also holds hand-written modules, so every edit to the logic recompiles
#      the generated code as well (a real case: ~58k hand-written lines next to
#      ~578k generated ones in ONE crate);
#   2. an oversized crate -- too many hand-written lines in one compilation
#      unit.
#
# Both are measured by SCANNING FILES, not by compiling: the two metrics cost
# one `cargo metadata` plus a read of the crates' `.rs` files, which is why
# `--quick` does not defer them.
#
# Ratchet, like every other metric: `codegen_mix` counts offending crates and
# `crate_size` counts the hand-written lines ABOVE the threshold, summed over
# the crates that exceed it. A repo full of pre-existing debt therefore reads
# the same number on both sides and passes; only a new mixed crate, or a crate
# crossing / growing past the threshold, makes the number go up.
#
# Source this file from rust/qg.sh AFTER lib/scope.sh (it reuses
# `_qg_rust_members`).

# Thresholds and codegen signatures live in the QG ruleset, never in a project
# file: `.qg.yaml` has no key for them, because the dev controls that file and a
# raised threshold would switch the check off. External override only, via
# QG_RULESET_DIR -- the same tamper rule as clippy.toml/rustfmt.toml.
_QG_LAYOUT_MAX_LINES_DEFAULT=5000
_QG_LAYOUT_CODEGEN_DEFAULT='slint_build::|tonic_build|tonic_prost_build|prost_build|bindgen::|cxx_build::|capnpc::|lalrpop'

_qg_layout_ruleset_file() {
  printf '%s\n' "$(qg_ruleset_dir)/crate-layout.toml"
}

# Hand-written lines a crate may hold before the excess is counted.
qg_layout_max_lines() {
  local f v=""
  f=$(_qg_layout_ruleset_file)
  if [ -f "$f" ]; then
    v=$(grep -E '^[[:space:]]*max_hand_written_lines[[:space:]]*=' "$f" 2>/dev/null \
        | head -1 | sed -E 's/.*=[[:space:]]*([0-9]+).*/\1/')
  fi
  printf '%s\n' "$(_num "${v:-$_QG_LAYOUT_MAX_LINES_DEFAULT}")"
}

# ERE of build-script contents that mean "this crate generates Rust".
qg_layout_codegen_re() {
  local f list=""
  f=$(_qg_layout_ruleset_file)
  if [ -f "$f" ]; then
    list=$(awk '
      /^[[:space:]]*codegen_entry_points[[:space:]]*=/ { inarr = 1 }
      inarr {
        n = split($0, parts, "\"")
        for (i = 2; i <= n; i += 2) print parts[i]
        if ($0 ~ /\]/) inarr = 0
      }
    ' "$f")
  fi
  if [ -z "$list" ]; then
    printf '%s\n' "$_QG_LAYOUT_CODEGEN_DEFAULT"
    return 0
  fi
  printf '%s' "$list" | sed '/^$/d' | tr '\n' '|' | sed 's/|$//'
  printf '\n'
}

# A file the language's own convention marks as generated is not hand-written
# (prost/tonic write `// This file is @generated by prost-build.`). Same law as
# the coverage profile: the marker is the convention, never a project setting.
_QG_LAYOUT_GENERATED_RE='@generated|^// Code generated .* DO NOT EDIT\.$|^//[[:space:]]*Automatically generated'

_qg_layout_is_generated() {
  head -5 "$1" 2>/dev/null | grep -qE "$_QG_LAYOUT_GENERATED_RE"
}

# Counts, per file: non-blank hand-written lines, and how many of those are NOT
# include-only. `include_only()` is what a `lib.rs` that merely includes the
# codegen output may hold -- comments, inner attributes, `use`, the include
# macros and their continuation lines; anything else is hand-written code, which
# is exactly what must not share a crate with codegen. The pattern is a regex
# LITERAL on purpose: passed through `awk -v`, the string would lose its
# backslashes to awk's own escape processing ("illegal primary").
#
# `#[cfg(test)] mod ... { ... }` blocks are dropped -- unit tests are not the
# crate's production weight. Brace counting is textual, so a brace inside a
# string literal in a test module can end the block early; both sides are
# scanned the same way, and the metric is a ratchet over that same number.
_QG_LAYOUT_AWK='
function include_only(l) {
  return l ~ /^[[:space:]]*(\/\/|\/\*|\*|#!?\[|\}|\)|;)/ ||
         l ~ /^[[:space:]]*(pub[[:space:]]+)?(use|extern[[:space:]]+crate)[[:space:]]/ ||
         l ~ /include!|include_modules!|include_proto!|include_wrapper!|concat!|env!/
}
FNR == 1 { skip = 0; depth = 0; armed = 0 }
{
  line = $0
  if (skip) {
    o = gsub(/\{/, "{", line); c = gsub(/\}/, "}", line)
    depth += o - c
    if (depth <= 0) { skip = 0; depth = 0 }
    next
  }
  if (line ~ /^[[:space:]]*#\[cfg\((all\(|any\()?test[,)]/) { armed = 1; next }
  if (armed) {
    if (line ~ /^[[:space:]]*$/) next
    if (line ~ /^[[:space:]]*(pub([[:space:]]*\([^)]*\))?[[:space:]]+)?mod[[:space:]]/) {
      armed = 0
      if (line ~ /\{/) {
        o = gsub(/\{/, "{", line); c = gsub(/\}/, "}", line)
        depth = o - c
        if (depth > 0) skip = 1
      }
      next
    }
    armed = 0
  }
  if (line ~ /^[[:space:]]*$/) next
  lines++
  if (!include_only(line)) nonallow++
}
END { printf "%d %d\n", lines + 0, nonallow + 0 }
'

# Build script of a crate, honoring a declared `build = "..."`. Prints its path;
# exit 1 when the crate has none.
_qg_layout_build_script() {
  local base="$1" declared=""
  declared=$(grep -E '^[[:space:]]*build[[:space:]]*=' "$base/Cargo.toml" 2>/dev/null \
             | head -1 | sed -E 's/.*=[[:space:]]*"([^"]+)".*/\1/')
  if [ -n "$declared" ] && [ "$declared" != "false" ] && [ -f "$base/$declared" ]; then
    printf '%s\n' "$base/$declared"
    return 0
  fi
  if [ -f "$base/build.rs" ]; then
    printf '%s\n' "$base/build.rs"
    return 0
  fi
  return 1
}

# qg_rust_layout_table <dir>
# One row per workspace member of <dir>:
#   <name>\t<root>\t<hand_lines>\t<non_include_only_lines>\t<is_codegen>
#
# `hand_lines` excludes: generated files, `tests/`, `benches/`, `examples/` and
# `build.rs` (each is its OWN compilation unit, so none of them is part of the
# crate's incremental weight), `tests.rs`, `target/`, and `#[cfg(test)]` module
# bodies. Nested members own their own files (longest-prefix), so a parent crate
# never inherits a child crate's lines.
#
# Exit 1 when the workspace cannot be enumerated -- the caller must turn that
# into a tool-error (exit 2), never into a metric: an empty member list on one
# side only would read as a regression.
qg_rust_layout_table() {
  local dir="$1"
  local members roots
  members=$(_qg_rust_members "$dir")
  [ -z "$members" ] && return 1
  roots=$(printf '%s\n' "$members" | cut -f2)

  local codegen_re
  codegen_re=$(qg_layout_codegen_re)

  local name root base rel relroot f r deeper files=() counts lines nonallow codegen bs
  while IFS=$'\t' read -r name root; do
    [ -z "$name" ] && continue
    base="$dir"
    [ -n "$root" ] && base="$dir/$root"
    [ -d "$base" ] || continue

    files=()
    while IFS= read -r f; do
      [ -z "$f" ] && continue
      rel="${f#"$base"/}"
      case "$rel" in
        target/*|*/target/*) continue ;;
        tests/*|*/tests/*) continue ;;
        benches/*|*/benches/*) continue ;;
        examples/*|*/examples/*) continue ;;
        build.rs|tests.rs|*/tests.rs) continue ;;
      esac
      relroot="$rel"
      [ -n "$root" ] && relroot="$root/$rel"
      deeper=0
      while IFS= read -r r; do
        [ -z "$r" ] && continue
        [ "$r" = "$root" ] && continue
        if [ "${#r}" -gt "${#root}" ] && [ "${relroot#"$r"/}" != "$relroot" ]; then
          deeper=1
          break
        fi
      done <<< "$roots"
      [ "$deeper" = "1" ] && continue
      _qg_layout_is_generated "$f" && continue
      files+=("$f")
    done < <(find "$base" -type f -name '*.rs' 2>/dev/null | sort)

    lines=0
    nonallow=0
    if [ "${#files[@]}" -gt 0 ]; then
      counts=$(awk "$_QG_LAYOUT_AWK" "${files[@]}" 2>/dev/null)
      lines=$(_num "$(printf '%s' "$counts" | awk '{print $1}')")
      nonallow=$(_num "$(printf '%s' "$counts" | awk '{print $2}')")
    fi

    codegen=0
    if bs=$(_qg_layout_build_script "$base") && grep -qE "$codegen_re" "$bs" 2>/dev/null; then
      codegen=1
    fi

    printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$root" "$lines" "$nonallow" "$codegen"
  done <<< "$members"
}

# measure_layout <dir> <log>
# ONE scan yields both metrics: "<codegen_mix> <crate_size_excess>". The log
# names every offending crate, so a regression says WHICH crate to split.
# Exit 1 = the workspace could not be enumerated (caller: tool-error).
measure_layout() {
  local dir="$1" log="$2"
  : > "$log"
  local table max
  table=$(qg_rust_layout_table "$dir") || return 1
  max=$(qg_layout_max_lines)
  # NOT `-v log=`: `log` is an awk BUILT-IN FUNCTION, so onetrue/BWK awk reads
  # the redirection target as log(0) and appends every offender line to a file
  # literally named `-inf` while the real log stays empty.
  printf '%s\n' "$table" | awk -F'\t' -v max="$max" -v logf="$log" '
    $5 == 1 && $4 > 0 {
      mix++
      printf "codegen_mix: crate %s (%s) mixes build.rs codegen with %d hand-written line(s) -- move the hand-written modules to a crate that depends on it\n", $1, ($2 == "" ? "." : $2), $4 >> logf
    }
    $3 > max {
      excess += $3 - max
      printf "crate_size: crate %s (%s) has %d hand-written lines, %d over the %d-line limit -- split it along an area boundary\n", $1, ($2 == "" ? "." : $2), $3, $3 - max, max >> logf
    }
    END { printf "%d %d\n", mix + 0, excess + 0 }
  '
}

# --- single-metric oracles ---------------------------------------------------
# `measure_layout` fuses both numbers into one scan; these two exist so the
# bats suite can assert that the fused pass reports exactly what measuring each
# metric on its own reports.

count_codegen_mix() {
  local dir="$1" log="${2:-/dev/null}"
  : > "$log"
  local table
  table=$(qg_rust_layout_table "$dir") || return 1
  printf '%s\n' "$table" | awk -F'\t' '$5 == 1 && $4 > 0 { n++ } END { printf "%d\n", n + 0 }'
}

count_crate_size() {
  local dir="$1" log="${2:-/dev/null}"
  : > "$log"
  local table max
  table=$(qg_rust_layout_table "$dir") || return 1
  max=$(qg_layout_max_lines)
  printf '%s\n' "$table" | awk -F'\t' -v max="$max" \
    '$3 > max { e += $3 - max } END { printf "%d\n", e + 0 }'
}
